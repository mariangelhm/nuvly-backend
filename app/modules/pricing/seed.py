def _variant(
    variant_code: str,
    name: str,
    variant_tier: str,
    product_type: str,
    sort_order: int,
    description: str = "",
    extra_price: int = 0,
) -> Dict[str, Any]:
    included_in_plans = {
        "core": ["essential", "plus", "pro"],
        "advanced": ["plus", "pro"],
        "premium": ["pro"],
    }[variant_tier]
    can_be_extra_in_plans = {
        "core": [],
        "advanced": [],
        "premium": ["plus"],
    }[variant_tier]
    resolved_extra_price = extra_price
    if variant_tier == "premium" and resolved_extra_price <= 0:
        resolved_extra_price = 3990 if product_type == "website" else 1990
    return {
        "variantCode": variant_code,
        "name": name,
        "description": description,
        "variantTier": variant_tier,
        "active": True,
        "includedInPlans": included_in_plans,
        "canBeExtraInPlans": can_be_extra_in_plans,
        "extraPrice": resolved_extra_price,
        "currency": "CLP",
        "sortOrder": sort_order,
    }


def _component(
    component_id: str,
    component_code: str,
    product_type: str,
    component_tier: str,
    sort_order: int,
    variants: List[Dict[str, Any]],
    name: str | None = None,
    description: str = "",
    category_code: str | None = None,
) -> Dict[str, Any]:
    return {
        "id": component_id,
        "componentCode": component_code,
        "productType": product_type,
        "categoryCode": category_code or component_code,
        "componentTier": component_tier,
        "name": name or component_code.replace("_", " ").replace("Beforeafter", "BeforeAfter").title(),
        "description": description,
        "active": True,
        "variants": variants,
        "sortOrder": sort_order,
    }


